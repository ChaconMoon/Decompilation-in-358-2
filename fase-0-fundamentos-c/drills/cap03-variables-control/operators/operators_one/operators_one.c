int i = 1; //  asignación
int main()
{
        // Operadores aritmeticos
        i + 3; // Suma.
        i - 8; // Resta.
        i * 9; // Multiplicación.
        i / 3; // Division
        i % 5; // Modulo (resto de la division)

        // Operadores abreviados
        i += 3; // Suma. (Lo mismo que i = i + 3)
        i -= 8; // Resta. (Lo mismo que i = i - 8)
        i *= 9; // Multiplicación. (Lo mismo que i = i * 9)
        i /= 2; // Division. (Lo mismo que i = i / 2)
        i %= 5; // Modulo. (Lo mismo que i = i % 5)
}
