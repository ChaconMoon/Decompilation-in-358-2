int i;
int main()
{
        // Post-incremento
        i++; // Suma uno a i (post-incremento)
        i--; // Resta uno a i (post-incremento)

        // Equivale a esto

        i += 1;
        i -= 1;

        // Pre-incremento

        ++i; // Suma 1 a i (pre-incremento)
        --i; // Suma 1 a i (pre-incremento)
}
